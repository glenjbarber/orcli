// TestNewThemeRefusesAnUnreadableColour covers the decision to error rather than
// fall back. A reader who wrote a wrong value and got the terminal theme back would
// conclude colour is off rather than that the value is wrong, and those are fixed
// differently.
func TestNewThemeRefusesAnUnreadableColour(t *testing.T) {
	if _, err := NewTheme("bad", "#gggggg", ""); err == nil {
		t.Error("a theme with an unreadable foreground was accepted")
	}
	if _, err := NewTheme("bad", "", "nonsense"); err == nil {
		t.Error("a theme with an unreadable background was accepted")
	}

	theme, err := NewTheme("partial", "", "#101010")
	if err != nil {
		t.Fatalf("a theme naming one side: %v", err)
	}
	if _, ok := theme.ForegroundRGB(); ok {
		t.Error("a theme naming no foreground reported one")
	}
	if _, ok := theme.BackgroundRGB(); !ok {
		t.Error("a theme naming a background did not report it")
	}
}

// TestSequenceWritesDirectRGB covers the reversal recorded in the design.
//
// The direct-RGB form rather than a 256-colour index, because the reason the mapping
// existed, Terminal.app support, did not survive the decision.
func TestSequenceWritesDirectRGB(t *testing.T) {
	got := RGB{R: 0x3b, G: 0x82, B: 0xf6}.Sequence()

	if want := "\x1b[38;2;59;130;246m"; got != want {
		t.Errorf("Sequence wrote %q, want %q", got, want)
	}
	if strings.Contains(got, "38;5;") {
		t.Errorf("Sequence wrote %q, want the direct-RGB form", got)
	}
}

// TestBackgroundSequenceIsABackground covers the one difference between the two forms,
// since writing a background as a foreground paints text rather than the ground behind
