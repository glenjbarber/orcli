// TestFaintDimIsAnAlternativeNotADefault covers the unverified case. Whether a
// terminal draws faint text is not known from here, so it is offered and the default
// stays a colour.
func TestFaintDimIsAnAlternativeNotADefault(t *testing.T) {
	plain := NewPalette(true, GroundDark, nil)
	faintDim := plain.WithFaintDim()

	if got := plain.Sequence(RoleDim); got == faintSequence {
		t.Error("dim defaults to the faint attribute")
	}
	if got := faintDim.Sequence(RoleDim); got != faintSequence {
		t.Errorf("the faint palette writes %q for dim, want the faint attribute", got)
	}

	// And only dim changes. The faint attribute is an alternative to one colour
	// and not to the table.
	if got, want := faintDim.Sequence(RoleChrome), plain.Sequence(RoleChrome); got != want {
		t.Errorf("faint changed chrome to %q, want %q", got, want)
	}
}

// TestRoleNameCoversEveryRole keeps a diagnostic honest. A role with no name is a role
// a message cannot identify.
func TestRoleNameCoversEveryRole(t *testing.T) {
	for _, role := range Roles() {
		name := RoleName(role)
		if name == "" || strings.HasPrefix(name, "role(") {
			t.Errorf("role %d reads as %q, want a name", int(role), name)
		}
	}
	if RoleName(Role(99)) == "" {
		t.Error("an unknown role has an empty name")
	}
}

// TestRGBRoundTrips covers the hex reading, since a theme is written by a reader and
// an authored colour has to land exactly.
func TestRGBRoundTrips(t *testing.T) {
	const hex = "#3b82f6"

	rgb, ok := RGBFromHex(hex)
	if !ok {
		t.Fatalf("RGBFromHex(%q) refused a well formed colour", hex)
	}
	if got := rgb.Hex(); got != hex {
		t.Errorf("the round trip gave %q, want %q", got, hex)
	}
}

