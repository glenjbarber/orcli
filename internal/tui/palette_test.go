// TestBothTablesCarryEveryRole is the check that catches a role added to one table
// and not the other.
//
// It is against the role list rather than against the other table, because two tables
// compared only to each other would both be missing the same role and the comparison
// would pass. A role rendered as chrome because a table lacked it is a row a reader
// cannot tell from the frame around it.
func TestBothTablesCarryEveryRole(t *testing.T) {
	for _, ground := range []Ground{GroundDark, GroundLight} {
		table := RoleTableFor(ground)
		for _, role := range Roles() {
			if _, ok := table[role]; !ok {
				t.Errorf("the %v table has no %s", ground, RoleName(role))
			}
		}
		if got, want := len(table), len(roleOrder); got != want {
			t.Errorf("the %v table carries %d roles, want %d", ground, got, want)
		}
	}
}

// TestTheThreeStatesAreDistinct is a property rather than a shape, and it is the one
// that decides whether a reader can read a refusal.
//
// Dim is present but not the point, failure is something went wrong, and approval is a
// question asking the reader to do something. A reader who cannot tell an approval
// from a failure cannot tell a question from a complaint.
func TestTheThreeStatesAreDistinct(t *testing.T) {
	for _, ground := range []Ground{GroundDark, GroundLight} {
		table := RoleTableFor(ground)
		t.Run(ground.String(), func(t *testing.T) {
			assertDistinct(t, table,
				[]Role{RoleDim, RoleFailure, RoleApproval},
				"the three state roles must not collide")
			assertDistinct(t, table,
				[]Role{RoleFailure, RoleApproval, RoleSuccess},
				"failure, approval and success must not collide")
		})
	}
}

// TestTheThreeToolIdentitiesAreDistinct covers the property that makes a tool line
// readable. A reader who cannot tell a file read from a command cannot read the log,
// so the three are separate roles and separate values.
func TestTheThreeToolIdentitiesAreDistinct(t *testing.T) {
	for _, ground := range []Ground{GroundDark, GroundLight} {
		table := RoleTableFor(ground)
		t.Run(ground.String(), func(t *testing.T) {
			assertDistinct(t, table,
				[]Role{RoleToolFS, RoleToolGit, RoleToolShell},
				"the three tool identities must not collide")

			// And against the states, since a tool line and a refusal are both
			// single rows in a log and the reader is looking at both.
			for _, tool := range []Role{RoleToolFS, RoleToolGit, RoleToolShell} {
				for _, state := range []Role{RoleDim, RoleFailure, RoleApproval} {
					if table[tool] == table[state] {
						t.Errorf("%s and %s are both %s",
							RoleName(tool), RoleName(state), table[tool].Hex())
					}
				}
			}
		})
	}
}

// assertDistinct reports each pair in a set that carries the same colour.
func assertDistinct(t *testing.T, table RoleTable, roles []Role, why string) {
	t.Helper()

	for i := range roles {
		for j := i + 1; j < len(roles); j++ {
			if table[roles[i]] == table[roles[j]] {
				t.Errorf("%s: %s and %s are both %s",
					why, RoleName(roles[i]), RoleName(roles[j]), table[roles[i]].Hex())
			}
		}
	}
}

// TestTheTwoGroundsReadDifferently checks that the second table is a table and not a
// copy. A light reader and a dark reader see different colours, and that is the
// reason there are two.
func TestTheTwoGroundsReadDifferently(t *testing.T) {
	dark, light := RoleTableFor(GroundDark), RoleTableFor(GroundLight)

	same := 0
	for _, role := range Roles() {
		if dark[role] == light[role] {
			same++
		}
	}
	if same == len(roleOrder) {
		t.Error("the two tables are identical, so one of them is not a table")
	}
	if same > len(roleOrder)/2 {
		t.Errorf("%d of %d roles carry the same colour in both tables",
			same, len(roleOrder))
	}
}

// TestTheLightTableIsDarker covers the reason the second table exists and is not
// generated by inverting the first.
//
// A value chosen to read as emphasis on a dark ground is unreadable as emphasis on a
// light one, so the light table holds darker values for the same roles rather than
// paler ones. A test on the average catches a table that got the direction wrong
// without a reader noticing.
func TestTheLightTableIsDarker(t *testing.T) {
	dark, light := RoleTableFor(GroundDark), RoleTableFor(GroundLight)

	var darkSum, lightSum float64
	for _, role := range Roles() {
		darkSum += float64(dark[role].R) + float64(dark[role].G) + float64(dark[role].B)
		lightSum += float64(light[role].R) + float64(light[role].G) + float64(light[role].B)
	}

	if lightSum >= darkSum {
		t.Errorf("the light table averages %.0f against the dark table's %.0f: it should be darker",
			lightSum/float64(len(roleOrder)*3), darkSum/float64(len(roleOrder)*3))
	}
}

// TestGroundIsLightJudgesByLuminance covers the choice of formula rather than an
// average.
//
// The eye is not equally sensitive to each channel, so an average calls a saturated
// blue brighter than a mid grey when it is not. This case is the one that separates
// the two: a mid grey sits above the midpoint on an average and below it on
// luminance.
func TestGroundIsLightJudgesByLuminance(t *testing.T) {
	cases := []struct {
		name string
		bg   string
		want bool
	}{
		{"white is light", "#ffffff", true},
		{"near-white is light", "#f5f5f5", true},
		{"mid grey is dark", "#808080", false},
		{"near-black is dark", "#0a0a0a", false},
		{"black is dark", "#000000", false},
		// A saturated blue is brighter than a mid grey as an average of the
		// channels and darker on luminance, which is the whole reason for the
		// formula. Judged as light, a blue background picks the wrong table.
		{"saturated blue is dark", "#0000ff", false},
		{"saturated yellow is light", "#ffff00", true},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			theme, err := NewTheme("test", "", c.bg)
			if err != nil {
				t.Fatalf("NewTheme: %v", err)
			}
			if got := groundIsLight(GroundAuto, &theme); got != c.want {
				t.Errorf("groundIsLight with background %s is %v, want %v",
					c.bg, got, c.want)
			}
		})
	}
}

// TestAnExplicitChoiceBeatsTheTheme covers the order, and each step of it is a
// reason. A reader who has said which ground they are on has said it more recently
// than a file did.
func TestAnExplicitChoiceBeatsTheTheme(t *testing.T) {
	onLight := themeWith(t, "", "#ffffff")
	onDark := themeWith(t, "", "#101010")

	if groundIsLight(GroundDark, &onLight) {
		t.Error("a light theme overrode an explicit dark")
	}
	if !groundIsLight(GroundLight, &onDark) {
		t.Error("a dark theme overrode an explicit light")
	}
}

// TestABackgroundThatCannotBeReadFallsToDark covers the case where the theme names
// none. A background the client cannot read is not a background it judges against.
func TestABackgroundThatCannotBeReadFallsToDark(t *testing.T) {
	if groundIsLight(GroundAuto, nil) {
		t.Error("no theme was read as light")
	}

	none := themeWith(t, "", "")
	if groundIsLight(GroundAuto, &none) {
		t.Error("a theme naming no background was read as light")
	}
}

// themeWith builds a theme and fails the test if it cannot.
func themeWith(t *testing.T, fg, bg string) Theme {
	t.Helper()

	theme, err := NewTheme("test", fg, bg)
	if err != nil {
		t.Fatalf("NewTheme(%q, %q): %v", fg, bg, err)
	}
	return theme
}

// TestParseGroundRefusesWhatItDoesNotKnow covers the decision to error rather than
// fall back.
//
// A reader who typed a word and got the default back would conclude the command
// ignored them, so an unrecognised ground is refused by name.
func TestParseGroundRefusesWhatItDoesNotKnow(t *testing.T) {
	for _, in := range []string{"auto", "AUTO", " dark ", "Light"} {
		if _, err := ParseGround(in); err != nil {
			t.Errorf("ParseGround(%q) returned %v, want it read", in, err)
		}
	}

	for _, in := range []string{"", "grey", "no", "lightt"} {
		_, err := ParseGround(in)
		if err == nil {
			t.Errorf("ParseGround(%q) was accepted, want a refusal", in)
			continue
		}
		if !strings.Contains(err.Error(), "auto, dark or light") {
			t.Errorf("the refusal is %q, want it to name what is allowed", err)
		}
	}
}

// TestColourOffWritesNothing is the property the plain-text contract rests on at the
// other end. A row is plain text and the colour travels beside it, so a palette with
// colour off contributes no bytes at all.
func TestColourOffWritesNothing(t *testing.T) {
	p := NewPalette(false, GroundDark, nil)

	for _, role := range Roles() {
		if got := p.Sequence(role); got != "" {
			t.Errorf("%s wrote %q with colour off", RoleName(role), got)
		}
	}
	if got := p.Base(); got != "" {
		t.Errorf("the base wrote %q with colour off", got)
	}
	if got := p.Reset(); got != bareReset {
		t.Errorf("the reset is %q, want the bare reset with colour off", got)
	}
}

// TestResetCarriesTheBase covers the case that a bare reset alone gets wrong.
//
// A bare reset clears the foreground and the background, so the rest of the row after
// it is drawn in the terminal theme rather than on the theme background. The reset is
// therefore the bare one followed by the base.
func TestResetCarriesTheBase(t *testing.T) {
	theme := themeWith(t, "#d0d0d0", "#101010")
	p := NewPalette(true, GroundDark, &theme)

	reset := p.Reset()
	if !strings.HasPrefix(reset, bareReset) {
		t.Errorf("the reset is %q, want it to begin with the bare reset", reset)
	}
	if !strings.HasSuffix(reset, p.Base()) {
		t.Errorf("the reset is %q, want it to end with the base %q", reset, p.Base())
	}
}

// TestTheGroundSettlesWithColourOff covers a small decision worth stating. A reader
// who asks which table would be read is answered without turning colour on, so the
// ground does not depend on the flag.
func TestTheGroundSettlesWithColourOff(t *testing.T) {
	light := themeWith(t, "", "#ffffff")

	if got := NewPalette(false, GroundAuto, &light).Ground(); got != GroundLight {
		t.Errorf("with colour off the ground is %v, want light", got)
	}
	if NewPalette(false, GroundAuto, &light).On() {
		t.Error("a palette built with colour off reports itself as on")
	}
}

// TestAnUnknownRoleReadsAsChrome covers the fallback. A row with no colour in it is
